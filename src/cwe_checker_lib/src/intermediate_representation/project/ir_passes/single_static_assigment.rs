pub const SPLIT_SYMBOL: &str = "__";

/// Computes register-SSA with a really crude approach
/// For each register used in the program, we add a phi instruction at the start of each block.
/// Will also replace temp variables generated by ghidra. Currently assuming that every temp
/// variable is only used within the original isntruction, so not crossing block boundaries.
/// This is not memory efficent. However, it is easy to restore SSA after adding an edge to the SSA:
/// Add the new varaibles to the phi functions of the receiving block.
///
/// ## SSA:
/// Every variable gets assigned once statically.
/// phi functions can join variables: new_var = phi(...)
/// phi: Var X ... X Var -> Var
///
/// ## How does it work?
/// - Add to every block phi functions for every register and rename all vars
/// - Get all incoming edges to the block
/// - Add at the start of the blocks each possible incoming edge to the phi functions
///
/// Supports: interprocedure calls, and interprocedure jumps (call/return). Might not support external calls
/// correctly.

pub type VarsAtEndOfBlock = HashMap<Tid, Vec<Variable>>;

pub struct SingleStaticAssigment {
    register_vars: Vec<Variable>,
    pub active_var_at_end_of_block: VarsAtEndOfBlock,
}

impl SingleStaticAssigment {
    fn get_used_register(&self, program: &Program) -> Vec<Variable> {
        // We need to aggregate all names, as we do the really crude method!
        let mut var_names = HashSet::new();
        for sub in &program.subs {
            for blks in sub.1.blocks() {
                for defs in blks.defs() {
                    match &defs.term {
                        Def::Load { var, .. } | Def::Assign { var, .. } => {
                            var_names.insert(var.clone())
                        }
                        Def::Store { .. } => false,
                    };
                }
            }
        }

        //let mut used_register_vars = Vec::new();

        //for register_var in &self.register_vars {
        //    // TODO: all temp variables are now used
        //    if var_names.contains(&register_var.name) || true {
        //        used_register_vars.push(register_var.clone());
        //    }
        //}

        //used_register_vars
        var_names.iter().map(|v| v.clone()).collect_vec()
    }
}

fn get_incoming_edges_for_each_blk(program: &Program) -> HashMap<String, HashSet<String>> {
    let mut cfg = get_program_cfg(program);
    cfg.reverse();
    let cfg_unreversed = get_program_cfg(program);
    // Saves the incoming edges for each block
    let mut incoming_edge_for_each_block = HashMap::<String, HashSet<String>>::new();
    for block in program.blocks() {
        incoming_edge_for_each_block.insert(block.tid.to_string(), HashSet::<String>::new());
    }

    for node in cfg.node_indices() {
        match cfg[node] {
            Node::BlkStart(_, _) => {
                let edges = cfg.edges(node);
                for edge in edges {
                    let target_node = edge.target();
                    if let Some(blk) = cfg[target_node].try_get_block() {
                        let incoming_edges = incoming_edge_for_each_block
                            .get_mut(&cfg[edge.source()].get_block().tid.to_string())
                            .expect("Blk had no key in incoming_edge_for_each_block, should never happen");
                        incoming_edges.insert(blk.tid.to_string());
                    }
                }
            }
            Node::CallSource { source, target } => {
                let source = source.0.tid.clone();
                let target = target.0.tid.clone();
                let incoming_edges = incoming_edge_for_each_block
                    .get_mut(&target.to_string())
                    .expect("Blk had no key in incoming_edge_for_each_block, should never happen");
                incoming_edges.insert(source.to_string());
            }
            Node::CallReturn { return_, .. } => {
                for edge in cfg_unreversed.edges(node) {
                    if let Edge::ReturnCombine(_) = edge.weight() {
                        let source = return_.0.tid.clone();
                        let target = cfg[edge.target()].get_block().tid.to_string();
                        let incoming_edges = incoming_edge_for_each_block
                            .get_mut(&target.to_string())
                            .expect("Blk had no key in incoming_edge_for_each_block, should never happen");
                        incoming_edges.insert(source.to_string());
                    }
                }
            }
            _ => (),
        }
    }

    incoming_edge_for_each_block
}

impl SingleStaticAssigment {
    fn rename_all_vars_and_add_empty_phi_fn(
        &mut self,
        program: &mut Program,
        used_register_vars: &Vec<Variable>,
    ) -> HashMap<String, HashMap<String, i64>> {
        // hashMap: [block_name][var_name] = curr_index
        let mut active_var_at_end_of_block = HashMap::<String, HashMap<String, i64>>::new();
        let mut active_indices = HashMap::<String, i64>::new();
        for var in used_register_vars {
            active_indices.insert(var.name.clone(), 0);
        }
        for block in program.blocks_mut() {
            let mut phi_instruction_at_begin = used_register_vars
                .iter()
                .map(|var| {
                    let new_var_index = active_indices[&var.name] + 1;
                    active_indices.insert(var.name.clone(), new_var_index);
                    Term {
                        tid: Tid::new_phi(&block.tid, &var.name),
                        term: Def::Assign {
                            var: Variable {
                                name: format!("{}{}{}", &var.name, SPLIT_SYMBOL, new_var_index),
                                size: var.size,
                                is_temp: var.is_temp,
                            },
                            // TODO fill in
                            value: Expression::Phi(vec![]),
                        },
                    }
                })
                .collect_vec();
            phi_instruction_at_begin.extend(block.defs.clone());
            block.defs = phi_instruction_at_begin;

            for def in &mut block.defs {
                for var in used_register_vars {
                    def.substitute_input_var(
                        &var,
                        &Expression::Var(Variable {
                            name: format!(
                                "{}{}{}",
                                var.name, SPLIT_SYMBOL, active_indices[&var.name]
                            ),
                            size: var.size,
                            is_temp: var.is_temp,
                        }),
                    )
                }
                match &mut def.term {
                    Def::Assign { var, .. } | Def::Load { var, .. } => {
                        if used_register_vars.contains(var) {
                            let new_var_index = active_indices[&var.name] + 1;
                            active_indices.insert(var.name.clone(), new_var_index);
                            var.name =
                                format!("{}{}{}", var.name, SPLIT_SYMBOL, new_var_index).to_owned();
                        }
                    }
                    _ => (),
                }
            }

            for jmp in &mut block.jmps_mut() {
                for var in used_register_vars {
                    jmp.term.substitute_input_var(
                        &var,
                        &Expression::Var(Variable {
                            name: format!(
                                "{}{}{}",
                                var.name, SPLIT_SYMBOL, active_indices[&var.name]
                            ),
                            size: var.size,
                            is_temp: var.is_temp,
                        }),
                    )
                }
            }

            let mut active_vars = vec![];
            for var in used_register_vars {
                active_vars.push(Variable {
                    name: format!("{}{}{}", var.name, SPLIT_SYMBOL, active_indices[&var.name]),
                    size: var.size,
                    is_temp: var.is_temp,
                });
            }

            active_var_at_end_of_block.insert(block.tid.to_string(), active_indices.clone());
            self.active_var_at_end_of_block
                .insert(block.tid.clone(), active_vars.clone());
        }
        active_var_at_end_of_block
    }
}

/// Renames all temp variables. temp varaibles are only used within one instruction but the name is
/// reused.*
///
/// * this is at moment a hypothesis.
fn rename_temp_variables(program: &mut Program) {
    let mut active_indices = HashMap::<Variable, i64>::new();

    for block in program.blocks_mut() {
        for def in &mut block.defs {
            for (var, index) in &active_indices {
                def.substitute_input_var(
                    &var,
                    &Expression::Var(Variable {
                        name: format!("{}{}{}", var.name, SPLIT_SYMBOL, active_indices[&var]),
                        size: var.size,
                        is_temp: true,
                    }),
                )
            }
            match &mut def.term {
                Def::Assign { var, .. } | Def::Load { var, .. } => {
                    if var.is_temp {
                        let new_var_index = active_indices.get(&var).unwrap_or(&0_i64) + 1;
                        active_indices.insert(var.clone(), new_var_index);
                        var.name =
                            format!("{}{}{}", var.name, SPLIT_SYMBOL, new_var_index).to_owned();
                    }
                }
                _ => (),
            }
        }

        for jmp in &mut block.jmps_mut() {
            for (var, index) in &active_indices {
                jmp.term.substitute_input_var(
                    &var,
                    &Expression::Var(Variable {
                        name: format!("{}{}{}", var.name, SPLIT_SYMBOL, index),
                        size: var.size,
                        is_temp: var.is_temp,
                    }),
                )
            }
        }
    }
    println!("Temp vars {}", active_indices.len());
}

fn fix_phi_functions(
    program: &mut Program,
    incoming_edge_for_each_block: HashMap<String, HashSet<String>>,
    active_var_at_end_of_block: HashMap<String, HashMap<String, i64>>,
) {
    for block in program.blocks_mut() {
        for incoming_edge_name in &incoming_edge_for_each_block[&block.tid.to_string()] {
            for def in block.defs_mut() {
                if let Term {
                    term:
                        Def::Assign {
                            var,
                            value: Expression::Phi(inputs),
                        },
                    ..
                } = def
                {
                    let original_name = var.name.split(SPLIT_SYMBOL).take(1).collect_vec()[0];
                    inputs.push(Variable {
                        name: format!(
                            "{}{}{}",
                            original_name,
                            SPLIT_SYMBOL,
                            active_var_at_end_of_block[&incoming_edge_name.clone()][original_name]
                        ),
                        size: var.size,
                        is_temp: var.is_temp,
                    })
                }
            }
        }
    }
}

impl IrPass for SingleStaticAssigment {
    const NAME: &'static str = "SingleStaticAssigment";

    const DBG_IR_FORM: super::prelude::debug::IrForm = IrForm::SingleStaticAssigment;

    type Input = Program;
    type ConstructionInput = Project;

    fn new(construction_input: &Self::ConstructionInput) -> Self {
        return SingleStaticAssigment {
            register_vars: construction_input
                .register_set
                .iter()
                .map(|var| var.clone())
                .clone()
                .collect_vec(),
            active_var_at_end_of_block: VarsAtEndOfBlock::new(),
        };
    }

    fn run(&mut self, mut program: &mut Self::Input) -> Vec<super::prelude::LogMessage> {
        let mut logs: Vec<LogMessage> = vec![];

        let mut last_time = Instant::now();
        eprintln!("Starting SSA Transform");
        eprintln!("Collecting used_register_vars: {:02?}", last_time.elapsed());
        last_time = Instant::now();

        let used_register_vars = self.get_used_register(&program);

        logs.push(LogMessage::new_info(format!(
            "Found following var names {}",
            itertools::join(&used_register_vars, ",")
        )));
        eprintln!("Incoming edge for each bloc: {:02?}", last_time.elapsed());
        last_time = Instant::now();

        let incoming_edge_for_each_block = get_incoming_edges_for_each_blk(&program);
        eprintln!("Active Var at the end of block: {:02?}", last_time.elapsed());
        last_time = Instant::now();

        let active_var_at_end_of_block =
            self.rename_all_vars_and_add_empty_phi_fn(&mut program, &used_register_vars);
        eprintln!("Fix PHI Functions: {:02?}", last_time.elapsed());
        last_time = Instant::now();

        fix_phi_functions(
            program,
            incoming_edge_for_each_block,
            active_var_at_end_of_block,
        );
        eprintln!("Done SSA: {:02?}", last_time.elapsed());
        //rename_temp_variables(program);

        logs
    }

    fn assert_postconditions(
        _construction_input: &Self::ConstructionInput,
        _program: &Self::Input,
    ) {
        todo!()
    }
}

