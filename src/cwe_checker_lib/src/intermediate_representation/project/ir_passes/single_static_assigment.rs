    fn assert_phi_function_content(phi_tid: &str, program: &Program, has_inputs: String) {
        let has_inputs = has_inputs.split(",").collect_vec();
        for blk in program.blocks() {
            for def in blk.defs() {
                if let Term {
                    term:
                        Def::Assign {
                            value: Expression::Phi(inputs),
                            ..
                        },
                    tid,
                } = def
                {
                    if phi_tid != tid.to_string() {
                        continue;
                    }
                    let mut has_inputs = has_inputs.clone();
                    has_inputs.sort();
                    let inputs = inputs.iter().map(|v| v.name.clone()).sorted().collect_vec();
                    assert!(
                        inputs.iter().zip(&has_inputs).all(|(a, b)| a == b),
                        "Missing input in Phi function {}",
                        phi_tid
                    );
                    return;
                }
            }
        }
        assert!(false, "phi_tid {} did not exist", phi_tid);
    }

    /// we built this code:
    /// x = 1; // blk1
    /// y = 2;
    /// if (x > 1) { // blk2
    ///     x = y;
    /// }
    /// y = 1 // blk3
    #[test]
    fn test_ssa() {
        let mut project = Project::mock_x64();
        let mut blk1 = Blk::default();
        blk1.defs = defs!["tid_1: RAX:8 = 0x1:1", "tid_2: RCX:8 = 0x2:1"];
        let mut blk1 = Term {
            tid: Tid::new("blk_1"),
            term: blk1,
        };

        let mut blk2 = Blk::default();
        blk2.defs = defs!["tid_3: RAX:8 = RCX:8"];

        let mut blk3 = Blk::default();
        blk3.defs = defs!["tid_4: RCX:8 = 0x1:1"];
        let blk3 = Term {
            tid: Tid::new("blk_3"),
            term: blk3,
        };

        let if_jmp = Jmp::CBranch {
            target: Tid::new("blk_2").clone(),
            condition: expr!("RAX:8 - 0x1:1"),
        };
        let if_jmp = Term {
            tid: Tid::new("foo_jmp_if"),
            term: if_jmp,
        };
        let else_jmp = Jmp::Branch(Tid::new(blk3.tid.clone()));
        let else_jmp = Term {
            tid: Tid::new("foo_jmp_else"),
            term: else_jmp,
        };
        blk1.term.add_jumps(vec![if_jmp, else_jmp]);
        let jmp_to_3 = Jmp::Branch(Tid::new(blk3.tid.clone()));
        let blk1_jmp = Term {
            tid: Tid::new("foo_jmp_else_2"),
            term: jmp_to_3,
        };
        blk2.add_jumps(vec![blk1_jmp]);
        let blk2 = Term {
            tid: Tid::new("blk_2"),
            term: blk2,
        };

        let mut sub = Sub::mock("main");
        sub.term.blocks.push(blk1);
        sub.term.blocks.push(blk2);
        sub.term.blocks.push(blk3);
        project.program.subs.insert(sub.tid.clone(), sub);

        for blk in project.program.blocks() {
            println!("{}", blk);
        }
        println!("====POST====");
        let mut logs = vec![];
        run_ir_pass![
            project.program,
            project,
            SingleStaticAssigment,
            logs,
            debug::Settings::default()
        ];
        assert_phi_function_content("phi_blk_1_RAX", &project.program.term, "".to_string());
        assert_phi_function_content("phi_blk_1_RCX", &project.program.term, "".to_string());
        assert_phi_function_content(
            "phi_blk_2_RAX",
            &project.program.term,
            format!("RAX{}2", SPLIT_SYMBOL).to_string(),
        );
        assert_phi_function_content(
            "phi_blk_2_RCX",
            &project.program.term,
            format!("RCX{}2", SPLIT_SYMBOL).to_string(),
        );
        assert_phi_function_content(
            "phi_blk_3_RAX",
            &project.program.term,
            format!("RAX{}2,RAX{}4", SPLIT_SYMBOL, SPLIT_SYMBOL).to_string(),
        );
        assert_phi_function_content(
            "phi_blk_3_RCX",
            &project.program.term,
            format!("RCX{}2,RCX{}3", SPLIT_SYMBOL, SPLIT_SYMBOL).to_string(),
        );
    }
